-- Oracle Database Schema for Pay Day Loan Module
-- Enterprise-Grade Normalized Schema

-- ============================================================================
-- 1. CORPORATE MASTER TABLE
-- ============================================================================
CREATE TABLE PDL_CORPORATE (
    CORPORATE_ID                 NUMBER(18) GENERATED BY DEFAULT AS IDENTITY,
    CORPORATE_CODE               VARCHAR2(30) NOT NULL,
    CORPORATE_NAME               VARCHAR2(200) NOT NULL,
    SHORT_NAME                   VARCHAR2(100),
    CUSTOMER_ID                  NUMBER(18),
    AGREEMENT_STATUS             VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    AGREEMENT_DATE               DATE,
    EFFECTIVE_FROM               DATE,
    EFFECTIVE_TO                 DATE,
    GUARANTEE_MODE               VARCHAR2(30) DEFAULT 'CORPORATE_GUARANTEE' NOT NULL,
    MAX_ELIGIBLE_PERCENT         NUMBER(5,2) DEFAULT 80 NOT NULL,
    SERVICE_CHARGE_PERCENT       NUMBER(5,2) DEFAULT 2 NOT NULL,
    MIN_SERVICE_CHARGE           NUMBER(18,2) DEFAULT 200 NOT NULL,
    MAX_ACTIVE_LOAN_PER_EMP      NUMBER(5) DEFAULT 1 NOT NULL,
    REPAYMENT_MODE               VARCHAR2(30) DEFAULT 'SALARY_DEDUCTION' NOT NULL,
    AUTO_DISBURSE_YN             NUMBER(1) DEFAULT 1 NOT NULL,
    STATUS                       VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    REMARKS                      VARCHAR2(500),
    CREATED_BY                   VARCHAR2(50) NOT NULL,
    CREATED_AT                   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY                   VARCHAR2(50),
    UPDATED_AT                   TIMESTAMP,
    CONSTRAINT PK_PDL_CORPORATE PRIMARY KEY (CORPORATE_ID),
    CONSTRAINT UK_PDL_CORPORATE_01 UNIQUE (CORPORATE_CODE),
    CONSTRAINT CK_PDL_CORPORATE_01 CHECK (AGREEMENT_STATUS IN ('PENDING','ACTIVE','SUSPENDED','EXPIRED','TERMINATED')),
    CONSTRAINT CK_PDL_CORPORATE_02 CHECK (STATUS IN ('ACTIVE','INACTIVE','SUSPENDED')),
    CONSTRAINT CK_PDL_CORPORATE_03 CHECK (AUTO_DISBURSE_YN IN (0,1))
);

CREATE INDEX IDX_PDL_CORPORATE_01 ON PDL_CORPORATE (CORPORATE_NAME);
CREATE INDEX IDX_PDL_CORPORATE_02 ON PDL_CORPORATE (STATUS, AGREEMENT_STATUS);
CREATE INDEX IDX_PDL_CORPORATE_03 ON PDL_CORPORATE (CUSTOMER_ID);

