CREATE INDEX IDX_PDL_REQ_01 ON PDL_LOAN_REQUEST (CORPORATE_ID, REQUEST_STATUS);
CREATE INDEX IDX_PDL_REQ_02 ON PDL_LOAN_REQUEST (EMPLOYEE_ID, REQUEST_STATUS);
